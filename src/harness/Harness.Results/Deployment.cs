namespace Harness.Results;

/// <summary>
/// A block's memory layout as a submission declares it. <b><see cref="Unstated"/> is the zero value and
/// is a REFUSAL</b>, for the reason the IR-side check already gives: absence means "no opinion", never a
/// default, and <b>TIA resolves no opinion to Optimized</b>. Undetermined is not clean.
/// </summary>
public enum DeclaredLayout
{
    /// <summary>Nobody said. Refused — a default here resolves to Optimized, which is invisible on the wire.</summary>
    Unstated = 0,

    /// <summary>Standard block access. The only layout classic S7comm can address at all.</summary>
    Standard,

    /// <summary>Optimized. <b>A REFUSAL</b>: the object is not an error on the wire, it is simply ABSENT.</summary>
    Optimized,

    /// <summary>The object has no layout attribute — a <c>%M</c> region, a tag table.</summary>
    NotApplicable,
}

/// <summary>One <c>(area, dbNumber)</c> pair a classic-S7comm path can address.</summary>
/// <remarks>
/// <c>Area</c> is compared ordinally and <c>DbNumber</c> numerically, because the write fence is scoped
/// on the AREA NAME drawn from the same hand-written map — so it verifies that the caller's claimed area
/// matches the tag's, never what KIND of object the area is.
/// </remarks>
public readonly record struct S7Reach(string Area, int DbNumber)
{
    public override string ToString() => $"{Area} (DB{DbNumber})";
}

/// <summary>
/// One row of <c>deployment.s7Objects</c>: an object a classic-S7comm path may reach, and the claims
/// about it.
/// </summary>
/// <param name="HarnessObject">
/// The HARNESS-GENERATED object this is. <b>A row naming a DELIVERABLE block is a REFUSAL, not a
/// finding</b> — the invariant itself. The harness touches harness-generated objects only.
/// </param>
/// <param name="LayoutSetAfterImport">
/// The <c>importStamp</c> that <c>--set Standard --yes</c> followed.
///
/// <para>*** A STAMP AND NOT A BOOLEAN, DELIBERATELY. *** A bool would be a caller-supplied verdict —
/// the exact shape this project has killed three times. A stamp can be COMPARED: if it does not equal
/// the current <c>importStamp</c>, the layout was re-asserted against a PREVIOUS import and has reverted
/// since. <b>"Nobody re-asserted it" and "re-asserted after the wrong import" then fall out as distinct
/// facts</b>, which is the whole reason for the choice.</para>
/// </param>
public sealed record S7ObjectDeclaration(
    string Area,
    int DbNumber,
    string HarnessObject,
    DeclaredLayout Layout,
    string? LayoutSetAfterImport)
{
    public S7Reach Reach => new(Area, DbNumber);
}

/// <summary>
/// <b>Contract §4.5 — a property of the DOWNLOAD, never of a vector.</b>
///
/// <para><c>s7Objects: []</c> is a POSITIVE CLAIM and is the NORMAL, CORRECT state: <i>no classic-S7comm
/// path in this deployment reaches any data block.</i> That is what a mirror-only wave looks like, and it
/// is CHECKED as a claim. <b>An absent <see cref="DeploymentDeclaration"/> is a different statement</b> —
/// nobody said — and is NOT CHECKED. The same absent-versus-empty distinction the conflict graph and the
/// timer presets already use.</para>
/// </summary>
/// <param name="ImportStamp">
/// Identifies the import the copy layer was generated by. Required whenever <see cref="S7Objects"/> is
/// non-empty, because every layout claim is dated against it.
/// </param>
public sealed record DeploymentDeclaration(string? ImportStamp, IReadOnlyList<S7ObjectDeclaration> S7Objects);

/// <summary>
/// What a tag map can reach, and the deliverable blocks it must not.
///
/// <para><b>Computed from the tag map, never declared by the vector author.</b> That is what makes gate
/// 11 a set-difference against an artifact nobody wrote for this purpose — the same shape as M4's
/// fidelity check and <c>trace</c>'s guard-containment hop.</para>
/// </summary>
/// <param name="Reachable">
/// Every distinct <c>(area, dbNumber)</c> the map addresses. <b>Null means no map was available</b>, and
/// gate 11 is then NOT CHECKED — an empty set would say "the map reaches nothing", which is the opposite
/// claim.
/// </param>
/// <param name="DeliverableObjects">
/// Names of blocks that SHIP. A row naming one is the invariant broken. Empty is legitimate — most
/// submissions do not know the deliverable set — and the gate says so rather than treating it as proof
/// that no row names one.
/// </param>
public sealed record TagMapReach(IReadOnlyCollection<S7Reach>? Reachable, IReadOnlySet<string> DeliverableObjects)
{
    public static TagMapReach None => new(null, new HashSet<string>(StringComparer.Ordinal));

    public static TagMapReach Of(IEnumerable<S7Reach> reachable, IEnumerable<string>? deliverables = null) =>
        new(reachable.Distinct().ToArray(),
            (deliverables ?? Array.Empty<string>()).ToHashSet(StringComparer.Ordinal));
}
